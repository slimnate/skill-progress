import {
    aliasesForSkillSlug,
    categorizeSkillIconSlug,
    skilliconsDevIconUrl,
    type SkillCategory,
} from './skillIconMeta';

export type { SkillCategory };

export type SkillIconEntry = {
    readonly slug: string;
    readonly aliases: readonly string[];
    readonly category: SkillCategory;
    readonly url: string;
};

function entry(
    slug: string,
    url: string,
    category: SkillCategory,
    extraAliases: readonly string[] = [],
): SkillIconEntry {
    const base = aliasesForSkillSlug(slug);
    const merged =
        base.length || extraAliases.length
            ? [...new Set([...base, ...extraAliases])]
            : [];
    return { slug, url, category, aliases: merged };
}

